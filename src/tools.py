import os
import sys
import io
from langchain_core.tools import tool
from logger import logger

# @tool tells LangChain that the LLM can use this function
@tool
def save_technical_note(file_name: str, content: str) -> str:
    """
    USEFUL FOR SAVING FILES.
    Creates and saves a technical note, documentation or report in the data/output folder.
    The file name must include the extension (e.g. summary.md, report.txt).
    """
    folder_path = "data/output"
    os.makedirs(folder_path, exist_ok=True)
    full_path = os.path.join(folder_path, file_name)

    try:
        with open(full_path, 'w', encoding='utf-8') as f:
            f.write(content)
        logger.info(f"File '{file_name}' created.")
        return f"File saved at {full_path}."
    except Exception as e:
        logger.error(f"Error in the save_technical_note tool: {e}")
        return f"Error trying to save the file: {e}"

@tool
def run_python_code(code: str) -> str:
    """
    USEFUL FOR ANALYZING DATA (CSV, JSON, EXCEL) OR DOING MATH.
    Receives a string with pure Python code, runs it locally and returns the console output (stdout).
    TIP FOR THE MODEL: the system prompt says which folder holds the repository files.
    Always use print() in your code to return results, because whatever is printed is captured and returned as the answer.
    """
    logger.info("The model called the Python interpreter. Running the generated code...")

    # Redirect standard output to capture the code's result
    old_stdout = sys.stdout
    redirected_output = sys.stdout = io.StringIO()

    try:
        # Run the string as if it were a real script
        exec(code)

        # Restore the terminal output
        sys.stdout = old_stdout
        result = redirected_output.getvalue()

        logger.info("Python code ran successfully.")
        return f"Execution result:\n{result}" if result else "Code ran, but produced no visible output."
    except Exception as e:
        sys.stdout = old_stdout
        logger.error(f"Error running the Python code generated by the model: {e}")
        return f"Error running the Python code: {e}. Review the syntax and try again."
